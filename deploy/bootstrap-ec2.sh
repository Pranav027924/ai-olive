#!/usr/bin/env bash
# One-time setup for a fresh Ubuntu EC2 instance that .github/workflows/deploy.yml
# deploys AI-OLive to. Safe to re-run: every step is skipped if already done.
#
#   ssh -i key.pem ubuntu@HOST 'bash -s' < deploy/bootstrap-ec2.sh
#
# Optional, prefixed inside the quotes (e.g. 'OLIVE_DOMAIN=app.example.com bash -s'):
#   OLIVE_DOMAIN  domain whose A record points at this box. Default:
#                 <public-ip>.sslip.io, which resolves to the box with no DNS
#                 setup and still gets a real Let's Encrypt cert from Caddy.
#   DEPLOY_DIR    default: ~/ai-olive (must match the DEPLOY_DIR repo secret)
#   SWAP_SIZE_GB  default: 4 (only added when the box has no swap)
#
# Writes DEPLOY_DIR/.env with freshly generated secrets. Provider API keys are
# NOT written: append e.g. ANTHROPIC_API_KEY=... to the .env afterwards.
# An existing .env is never overwritten.
set -euo pipefail

DEPLOY_DIR="${DEPLOY_DIR:-$HOME/ai-olive}"
SWAP_SIZE_GB="${SWAP_SIZE_GB:-4}"

log() { printf '\n==> %s\n' "$*"; }

# --- 1. Docker + compose plugin ------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  log "Installing Docker"
  curl -fsSL https://get.docker.com | sudo sh
else
  log "Docker already installed: $(docker --version)"
fi
sudo systemctl enable --now docker >/dev/null
# Group membership applies to new SSH sessions (the deploy workflow opens one).
sudo usermod -aG docker "$USER"

# --- 2. Swap (ClickHouse + the whisper-bundling chat image are memory-hungry) --
if [ "$(swapon --show --noheadings | wc -l)" -eq 0 ]; then
  log "Adding ${SWAP_SIZE_GB}G swap at /swapfile"
  sudo fallocate -l "${SWAP_SIZE_GB}G" /swapfile
  sudo chmod 600 /swapfile
  sudo mkswap /swapfile >/dev/null
  sudo swapon /swapfile
  grep -q '^/swapfile ' /etc/fstab || echo '/swapfile none swap sw 0 0' | sudo tee -a /etc/fstab >/dev/null
else
  log "Swap already present"
fi

# --- 3. Sanity checks -------------------------------------------------------------
disk_gb=$(df -BG --output=size / | tail -1 | tr -dc '0-9')
mem_mb=$(free -m | awk '/^Mem:/ {print $2}')
log "Root disk: ${disk_gb}G, RAM: ${mem_mb}M"
if [ "$disk_gb" -lt 20 ]; then
  echo "WARNING: <20G disk; images + volumes may not fit. Grow the EBS volume to 30G." >&2
fi
if [ "$mem_mb" -lt 3500 ]; then
  echo "WARNING: <4G RAM; ClickHouse and chat-service may be OOM-killed." >&2
fi

# --- 4. Domain ----------------------------------------------------------------------
if [ -z "${OLIVE_DOMAIN:-}" ]; then
  imds=http://169.254.169.254/latest
  token=$(curl -fsS -X PUT "$imds/api/token" -H 'X-aws-ec2-metadata-token-ttl-seconds: 60')
  public_ip=$(curl -fsS -H "X-aws-ec2-metadata-token: $token" "$imds/meta-data/public-ipv4")
  OLIVE_DOMAIN="${public_ip//./-}.sslip.io"
fi
log "Domain: $OLIVE_DOMAIN"

# --- 5. Deploy dir + .env ---------------------------------------------------------
mkdir -p "$DEPLOY_DIR"
cd "$DEPLOY_DIR"
if [ -f .env ]; then
  log "$DEPLOY_DIR/.env already exists; leaving it untouched"
else
  log "Writing $DEPLOY_DIR/.env with generated secrets"
  # Hex secrets: no characters that need quoting in .env, URLs or SQL.
  gen() { openssl rand -hex "${1:-24}"; }
  minio_pw=$(gen)
  ingest_key=$(gen)
  umask 077
  cat > .env <<EOF
# Generated by deploy/bootstrap-ec2.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep secret.
# The deploy workflow appends/refreshes IMAGE_PREFIX and TAG below.

# --- domain / TLS ---
OLIVE_DOMAIN=$OLIVE_DOMAIN

# --- auth ---
DISABLE_AUTH=false
JWT_SECRET=$(gen 32)
JWT_ALGORITHM=HS256

# --- postgres ---
POSTGRES_USER=olive
POSTGRES_PASSWORD=$(gen)
POSTGRES_DB=olive

# --- minio / s3 (S3_SECRET_KEY must equal MINIO_ROOT_PASSWORD) ---
MINIO_ROOT_USER=olive
MINIO_ROOT_PASSWORD=$minio_pw
S3_BUCKET=olive-attachments
S3_REGION=us-east-1
S3_ACCESS_KEY=olive
S3_SECRET_KEY=$minio_pw

# --- clickhouse ---
CLICKHOUSE_USER=olive
CLICKHOUSE_PASSWORD=$(gen)
CLICKHOUSE_DB=olive

# --- inter-service ---
INGESTION_API_KEY=$ingest_key
INGESTION_API_KEYS=$ingest_key

# --- providers: append the keys you use, e.g. ANTHROPIC_API_KEY=sk-ant-... ---
EOF
fi

log "Bootstrap complete. Next: add provider keys to $DEPLOY_DIR/.env, then run the Deploy workflow."
